/** Keys of the editor messages. */
export type EditorKey = keyof typeof editorsEn;

/**
 * A language's editor messages. Plural forms are optional here so each language can list the forms its
 * grammar needs; the language's full `Messages` type checks that every required key is there.
 */
type EditorPlural = EditorKey extends infer K ? (K extends `${infer B}.other` ? B : never) : never;
export type EditorMessages = Partial<
  Record<EditorKey | `${EditorPlural}.${"zero" | "one" | "two" | "few" | "many"}`, string>
>;
