/**
 * A language's tables messages. Plural forms are optional here so each language can list the forms its
 * grammar needs; the language's full `Messages` type checks that every required key is there.
 */
type TablesPlural = TablesKey extends infer K ? (K extends `${infer B}.other` ? B : never) : never;
export type TablesMessages = Partial<
  Record<TablesKey | `${TablesPlural}.${"zero" | "one" | "two" | "few" | "many"}`, string>
>;
