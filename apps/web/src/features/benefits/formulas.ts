/**
 * The editable formulas of the benefit tables (ADR-0040). Each formula has a default, the variables it can
 * use, and where it is applied (per station, per building or per line). A project's own formulas are saved
 * in the drawing kind `benefits`; "Reset" brings the default back.
 */
import { formulaProblem } from "./formula";

/** A variable a formula can use: data from the map, or a parameter of the assumption library. */
export interface FormulaVar {
  name: string;
  label: string;
  /** Assumption library key when the variable is a parameter (it then varies between low and high). */
  param?: string;
}

export type FormulaId =
  | "ridership_daily"
  | "ridership_annual"
  | "gdp"
  | "earnings"
  | "land_value"
  | "property_tax"
  | "construction_gdp"
  | "construction_jobs"
  | "operation_gdp"
  | "operation_jobs";

export interface FormulaDef {
  id: FormulaId;
  label: string;
  /** What one evaluation stands for. */
  per: string;
  unit: string;
  default: string;
  vars: FormulaVar[];
}

const v = (name: string, label: string, param?: string): FormulaVar =>
  param ? { name, label, param } : { name, label };

