export const FORMULA_BY_ID = Object.fromEntries(FORMULAS.map((f) => [f.id, f])) as Record<
  FormulaId,
  FormulaDef
>;

/** The benefit tables' own settings (drawing kind `benefits`): the project's formulas. */
export interface BenefitsDoc {
  formulas?: Partial<Record<FormulaId, string>>;
}

/** Purpose: the formula a project uses: its own when it compiles, else the default. */
export function formulaText(doc: BenefitsDoc | null | undefined, id: FormulaId): string {
  const own = doc?.formulas?.[id];
  const def = FORMULA_BY_ID[id];
  if (
    own &&
    !formulaProblem(
      own,
      def.vars.map((x) => x.name),
    )
  )
    return own;
  return def.default;
}
