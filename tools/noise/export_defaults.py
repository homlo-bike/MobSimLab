#!/usr/bin/env python3
"""Export the noise plugin's parameters for the noise engine (ADR-0038).

Usage:
  python3 tools/noise/export_defaults.py           # write crates/noise/data/defaults.json
  python3 tools/noise/export_defaults.py --check   # fail if it is stale

Reads plugins/noise/assumptions/parameters.yaml (validated by tools/plugins/check.py) and writes every
numeric noise.* parameter as [low, central, high] for "*" and each core mode whose value differs, and
every enum noise.* parameter the same way under "enums". Values for a plugin mode (cable car, aerial tramway,
ferry) go under the mode id, and under "<mode>/<context value>" when they are for one system or vessel type
(the engine looks those up for point sources, most specific first).
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "plugins" / "noise" / "assumptions" / "parameters.yaml"
OUT = ROOT / "crates" / "noise" / "data" / "defaults.json"


def assumption_check():
    """tools/assumptions/check.py as a module (its mode list and resolve rule)."""
    spec = importlib.util.spec_from_file_location(
        "assumption_check", ROOT / "tools" / "assumptions" / "check.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render() -> str:
    ac = assumption_check()
    params = yaml.safe_load(SRC.read_text(encoding="utf-8")) or []
    out: dict = {}
    enums: dict = {}
    for p in params:
        kind = p.get("kind", "number")
        if not p["key"].startswith("noise.") or kind not in ("number", "enum"):
            continue
        row = {}
        for m in ["*", *ac.MODES]:
            v = ac.resolve(p, m)
            row[m] = [
                v.get("low", v["central"]),
                v["central"],
                v.get("high", v["central"]),
            ]
        for v in p["values"]:
            ctx = v["context"]
            modes = [
                m for m in ac.as_list(ctx["mode"]) if m != "*" and m not in ac.MODES
            ]
            other = [x for k, x in ctx.items() if k != "mode"]
            if not modes or len(other) > 1:
                continue
            for m in modes:
                for o in ac.as_list(other[0]) if other else [None]:
                    row[m if o is None else f"{m}/{o}"] = [
                        v.get("low", v["central"]),
                        v["central"],
                        v.get("high", v["central"]),
                    ]
        glob = row["*"]
        (enums if kind == "enum" else out)[p["key"]] = {
            k: x for k, x in row.items() if k == "*" or x != glob
        }
    data = {
        "_comment": "Generated by tools/noise/export_defaults.py from plugins/noise/assumptions/parameters.yaml. Do not edit by hand.",
        "params": out,
        "enums": enums,
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run tools/noise/export_defaults.py",
                file=sys.stderr,
            )
            return 1
        print("OK: noise defaults up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
