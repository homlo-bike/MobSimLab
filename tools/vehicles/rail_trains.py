"""Write the railway editor's train list from the vehicle catalogue.

The railway editor offers the catalogue's rail vehicles for service lines. The web app does not read
``vehicles/`` at run time (the container image does not ship it), so this script copies the values the
running-time estimate needs into ``apps/web/src/features/railways/trains.ts``:

- length, top speed, power and empty mass, as the catalogue files give them (power and mass may be
  missing; ``rail_plan::service::train_params`` then estimates them by mode);
- planning capacity: seats plus the standing area at the mode's planning density
  (``mode.standing_density_ppm2`` in ``assumptions/DEFAULTS.md``; 08-vehicles.md §3 rule 4).

Usage:
    python tools/vehicles/rail_trains.py          # rewrite trains.ts
    python tools/vehicles/rail_trains.py --check  # fail if trains.ts is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps/web/src/features/railways/trains.ts"
# Catalogue folder → rail mode id, in the editor's mode order.
FOLDERS = {
    "tram": "tram",
    "light-rail": "light_rail",
    "metro": "metro",
    "commuter-rail": "commuter_rail",
    "regional-rail": "regional_rail",
    "long-distance-rail": "long_distance_rail",
    "high-speed-rail": "high_speed_rail",
}
# mode.standing_density_ppm2, central values (assumptions/DEFAULTS.md, mode table).
STANDING_DENSITY = {
    "tram": 4,
    "light_rail": 4,
    "metro": 4,
    "commuter_rail": 4,
    "regional_rail": 2,
    "long_distance_rail": 0,
    "high_speed_rail": 0,
}


def value(v: dict, key: str) -> float | None:
    """Purpose: the numeric value of a catalogue quantity, or None when absent."""
    q = v.get(key)
    if isinstance(q, dict) and isinstance(q.get("value"), (int, float)):
        return float(q["value"])
    return None


def trains() -> list[dict]:
    """Purpose: one entry per catalogue rail vehicle, by mode then name."""
    out = []
    for folder, mode in FOLDERS.items():
        for f in sorted((ROOT / "vehicles" / folder).glob("*.json")):
            v = json.loads(f.read_text(encoding="utf-8"))
            length = value(v, "length")
            top = value(v, "topSpeed")
            if not length or not top:
                continue
            seats = value(v, "seats") or 0
            standing = (value(v, "standingArea") or 0) * STANDING_DENSITY[mode]
            mass = value(v, "weightEmpty")  # t
            power = value(v, "power")  # kW
            out.append(
                {
                    "id": f.stem,
                    "name": v["name"],
                    "mode": mode,
                    "length_m": round(length, 2),
                    "top_speed_kmh": round(top, 1),
                    "power_kw": round(power, 1) if power else None,
                    "empty_mass_t": round(mass, 1) if mass else None,
                    "capacity": round(seats + standing),
                }
            )
    out.sort(key=lambda t: (list(FOLDERS.values()).index(t["mode"]), t["name"]))
    return out


def render(items: list[dict]) -> str:
    """Purpose: the TypeScript module text."""
    rows = "\n".join(f"  {json.dumps(t, ensure_ascii=False)}," for t in items)
    return (
        "// Generated by tools/vehicles/rail_trains.py from vehicles/ (CC BY 4.0). Do not edit.\n"
        'import type { CatalogueTrain } from "./types";\n\n'
        "/** Rail vehicles of the catalogue, by mode, for service lines. */\n"
        f"export const TRAINS: CatalogueTrain[] = [\n{rows}\n];\n"
    )


def main() -> int:
    """Purpose: write trains.ts, or with --check report whether it is current."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if trains.ts is out of date")
    a = ap.parse_args()
    text = render(trains())
    if a.check:
        if OUT.read_text(encoding="utf-8") != text:
            rel = OUT.relative_to(ROOT)
            print(f"{rel} is out of date: run python tools/vehicles/rail_trains.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
