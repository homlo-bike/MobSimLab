"""Write the street line tool's vehicle list from the vehicle catalogue.

The street line tool offers the catalogue's buses, BRT vehicles, trolleybuses and coaches. The web app
does not read ``vehicles/`` at run time (the container image does not ship it), so this script copies the
values the tool needs into ``apps/web/src/features/street-lines/vehicles.ts``:

- length, height and top speed, which replace the mode's routing profile (road checks, running times);
- loaded weight for weight limits: the catalogue's ``weightLoaded``, else the empty weight plus 75 kg per
  passenger place, else none (the mode's profile weight then stays);
- planning capacity: seats plus the standing area at the mode's planning density
  (``mode.standing_density_ppm2`` in ``assumptions/DEFAULTS.md``; 08-vehicles.md §3 rule 4);
- for depot layouts: width, articulations, axle positions and turning circle (the swept-path check)
  and the energy source (battery vehicles charge in the depot).

Usage:
    python tools/vehicles/street_vehicles.py          # rewrite vehicles.ts
    python tools/vehicles/street_vehicles.py --check  # fail if vehicles.ts is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps/web/src/features/street-lines/vehicles.ts"
# Catalogue folder → street mode id, in the tool's mode order.
FOLDERS = {
    "bus": "bus",
    "brt": "brt",
    "trolleybus": "trolleybus",
    "intercity-bus": "intercity_bus",
}
# mode.standing_density_ppm2, central values (assumptions/DEFAULTS.md, mode table).
STANDING_DENSITY = {"bus": 4, "brt": 4, "trolleybus": 4, "intercity_bus": 0}
# Mass of one passenger for the loaded weight when the catalogue has only the empty weight, t.
PASSENGER_T = 0.075


def value(v: dict, key: str) -> float | None:
    """Purpose: the numeric value of a catalogue quantity, or None when absent."""
    q = v.get(key)
    if isinstance(q, dict) and isinstance(q.get("value"), (int, float)):
        return float(q["value"])
    return None


def vehicles() -> list[dict]:
    """Purpose: one entry per catalogue street vehicle, by mode then name."""
    out = []
    for folder, mode in FOLDERS.items():
        for f in sorted((ROOT / "vehicles" / folder).glob("*.json")):
            v = json.loads(f.read_text(encoding="utf-8"))
            length = value(v, "length")
            top = value(v, "topSpeed")
            if not length or not top:
                continue
            seats = value(v, "seats") or 0
            capacity = round(seats + (value(v, "standingArea") or 0) * STANDING_DENSITY[mode])
            height = value(v, "height")
            loaded = value(v, "weightLoaded")
            empty = value(v, "weightEmpty")
            weight = loaded if loaded else (empty + capacity * PASSENGER_T if empty else None)
            consist = v.get("consist") or {}
            axles = (consist.get("axlePositions") or {}).get("value")
            turning = value(v, "turningCircle")
            energy = (v.get("energySource") or {}).get("value")
            out.append(
                {
                    "id": f.stem,
                    "name": v["name"],
                    "mode": mode,
                    "length_m": round(length, 2),
                    "height_m": round(height, 2) if height else None,
                    "weight_t": round(weight, 1) if weight else None,
                    "top_speed_kmh": round(top, 1),
                    "capacity": capacity,
                    "width_m": round(value(v, "width") or 2.55, 2),
                    "articulations": int(value(consist, "articulations") or 0),
                    "axles_m": [round(float(a), 3) for a in axles]
                    if isinstance(axles, list) and axles
                    else None,
                    "turning_circle_m": round(turning, 2) if turning else None,
                    "energy": energy if isinstance(energy, str) else None,
                }
            )
    out.sort(key=lambda t: (list(FOLDERS.values()).index(t["mode"]), t["name"]))
    return out


def render(items: list[dict]) -> str:
    """Purpose: the TypeScript module text."""
    rows = "\n".join(f"  {json.dumps(t, ensure_ascii=False)}," for t in items)
    return (
        "// Generated by tools/vehicles/street_vehicles.py from vehicles/ (CC BY 4.0). Do not edit.\n"
        'import type { CatalogueVehicle } from "./types";\n\n'
        "/** Street vehicles of the catalogue, by mode, for street lines. */\n"
        f"export const VEHICLES: CatalogueVehicle[] = [\n{rows}\n];\n"
    )


def main() -> int:
    """Purpose: write vehicles.ts, or with --check report whether it is current."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if vehicles.ts is out of date")
    a = ap.parse_args()
    text = render(vehicles())
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            rel = OUT.relative_to(ROOT)
            print(f"{rel} is out of date: run python tools/vehicles/street_vehicles.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
