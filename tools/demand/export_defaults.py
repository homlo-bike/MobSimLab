#!/usr/bin/env python3
"""Export the demand model parameters for Project preferences and the worker (ADR-0019, 09 §2).

Usage:
  python3 tools/demand/export_defaults.py           # write the two files below
  python3 tools/demand/export_defaults.py --check   # fail if either is stale

Reads assumptions/parameters (validated by tools/assumptions/check.py) and writes every `demand.*` parameter,
with the walking and cycling speeds the model uses, as [low, central, high] with its label, unit, basis,
sources and the model step it belongs to:

- apps/web/src/features/demand/defaults.generated.json: the Demand section of Project preferences, which
  shows and edits them (a project's own value is kept in its preferences under the key);
- worker/src/mobsim_worker/demand/defaults.json: the values the worker falls back to for any key a run does
  not set.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB_OUT = (
    ROOT / "apps" / "web" / "src" / "features" / "demand" / "defaults.generated.json"
)
WORKER_OUT = ROOT / "worker" / "src" / "mobsim_worker" / "demand" / "defaults.json"

#: Parameters of other groups that the demand model uses, besides `demand.*`.
EXTRA = ["demand.walk_speed_kmh", "analysis.cycle_speed_kmh"]

#: Model step of a key, by prefix (first match wins), in the order Project preferences shows them.
STEPS = [
    ("zones", ("demand.area_buffer_m", "demand.zone_")),
    ("generation", ("demand.trip_rate.", "demand.attraction.", "demand.cbd_")),
    ("periods", ("demand.period.", "demand.period_share.", "demand.from_home_share.")),
    ("distribution", ("demand.deterrence.", "demand.intrazonal_")),
    (
        "mode_choice",
        (
            "demand.mode.",
            "demand.vot.",
            "demand.walk_speed_kmh",
            "analysis.cycle_speed_kmh",
        ),
    ),
    ("assignment", ("demand.car_occupancy", "demand.road.", "demand.feedback.")),
]


def assumption_check():
    """tools/assumptions/check.py as a module (its parameter loader and resolve rule)."""
    spec = importlib.util.spec_from_file_location(
        "assumption_check", ROOT / "tools" / "assumptions" / "check.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def step_of(key: str) -> str:
    for step, prefixes in STEPS:
        if key.startswith(prefixes):
            return step
    raise SystemExit(f"{key}: no demand model step; add its prefix to STEPS")


def collect() -> list[dict]:
    ac = assumption_check()
    out = []
    for p in ac.load_parameters():
        key = p["key"]
        if not (key.startswith("demand.") or key in EXTRA):
            continue
        v = ac.resolve(p, "*")
        out.append(
            {
                "key": key,
                "step": step_of(key),
                "label": p["label"],
                "unit": p["unit"],
                "values": [
                    v.get("low", v["central"]),
                    v["central"],
                    v.get("high", v["central"]),
                ],
                "basis": v["basis"],
                "sources": v["sources"],
            }
        )
    order = {s: i for i, (s, _) in enumerate(STEPS)}
    return sorted(out, key=lambda r: order[r["step"]])


def render() -> tuple[str, str]:
    rows = collect()
    web = {
        "_comment": "Generated by tools/demand/export_defaults.py from assumptions/parameters. Do not edit by hand.",
        "steps": [s for s, _ in STEPS],
        "params": rows,
    }
    worker = {
        "_comment": "Generated by tools/demand/export_defaults.py from assumptions/parameters. Do not edit by hand.",
        "values": {r["key"]: r["values"][1] for r in rows},
    }
    dump = lambda d: json.dumps(d, indent=1, ensure_ascii=False) + "\n"
    return dump(web), dump(worker)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    texts = dict(zip((WEB_OUT, WORKER_OUT), render(), strict=True))
    if a.check:
        stale = [
            p
            for p, t in texts.items()
            if not p.exists() or p.read_text(encoding="utf-8") != t
        ]
        for p in stale:
            print(
                f"{p.relative_to(ROOT)} is stale; run tools/demand/export_defaults.py",
                file=sys.stderr,
            )
        if stale:
            return 1
        print("OK: demand defaults up to date")
        return 0
    for p, t in texts.items():
        p.write_text(t, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
