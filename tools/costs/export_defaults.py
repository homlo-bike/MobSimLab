#!/usr/bin/env python3
"""Export the cost unit values for the web app's cost tables (ADR-0039).

Usage:
  python3 tools/costs/export_defaults.py           # write apps/web/src/features/costs/defaults.generated.json
  python3 tools/costs/export_defaults.py --check   # fail if it is stale

Reads assumptions/parameters/costs.yaml (validated by tools/assumptions/check.py) and mode.spare_share
from modes.yaml, and writes every parameter as [low, central, high] for "*" and each mode whose value
differs, with its label and unit, so the tables can show and edit them.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps" / "web" / "src" / "features" / "costs" / "defaults.generated.json"
EXTRA = {"mode.spare_share", "mode.vehicle_capacity"}


def assumption_check():
    """tools/assumptions/check.py as a module (its parameter loader, mode list and resolve rule)."""
    spec = importlib.util.spec_from_file_location(
        "assumption_check", ROOT / "tools" / "assumptions" / "check.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render() -> str:
    ac = assumption_check()
    out: dict = {}
    for p in ac.load_parameters():
        if not (p["key"].startswith("cost.") or p["key"] in EXTRA):
            continue
        row = {}
        for m in ["*", *ac.MODES]:
            v = ac.resolve(p, m)
            row[m] = [
                v.get("low", v["central"]),
                v["central"],
                v.get("high", v["central"]),
            ]
        glob = row["*"]
        out[p["key"]] = {
            "label": p["label"],
            "unit": p["unit"],
            "values": {k: x for k, x in row.items() if k == "*" or x != glob},
        }
    data = {
        "_comment": "Generated by tools/costs/export_defaults.py from assumptions/parameters. Do not edit by hand.",
        "params": out,
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run tools/costs/export_defaults.py",
                file=sys.stderr,
            )
            return 1
        print("OK: cost defaults up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
