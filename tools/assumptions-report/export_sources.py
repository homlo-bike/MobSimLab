#!/usr/bin/env python3
"""Export where every assumption library value comes from, for the assumptions report (FR-ASM-04).

Usage:
  python3 tools/assumptions-report/export_sources.py           # write apps/web/src/workspace/assumptions-report.generated.json
  python3 tools/assumptions-report/export_sources.py --check   # fail if it is stale

Reads assumptions/parameters and assumptions/sources.yaml (validated by tools/assumptions/check.py), and the
number parameters and sources of the plugins whose values Project Preferences shows (as
tools/parameters/export_defaults.py does), and writes,
per parameter, what it is used by and, for every mode ("*" and each mode) and each traction with its own entry,
the entry that applies: its basis, check, sources and reasoning. The values themselves come from
parameters.generated.json (tools/parameters/export_defaults.py), so they are not repeated here. Also writes
the sources the entries cite, with title, publisher, link and access.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps" / "web" / "src" / "workspace" / "assumptions-report.generated.json"
# Plugins whose number parameters are in Project Preferences (PLUGINS in tools/parameters/export_defaults.py).
PLUGINS = ["noise", "aerial-lift", "ferry", "on-demand-bus", "energy"]


def read_yaml(path: Path) -> list[dict]:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or []


def assumption_check():
    """tools/assumptions/check.py as a module (its loaders, mode list and resolve rule)."""
    spec = importlib.util.spec_from_file_location(
        "assumption_check", ROOT / "tools" / "assumptions" / "check.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def entry(v: dict) -> dict:
    return {
        "basis": v["basis"],
        "check": v.get("check", "unverified"),
        "sources": list(v.get("sources", [])),
        "rationale": " ".join(str(v.get("rationale", "")).split()),
    }


def index(entries: list[dict], v: dict) -> int:
    """Position of a value entry's source details in `entries`, added when new."""
    e = entry(v)
    if e not in entries:
        entries.append(e)
    return entries.index(e)


def render() -> str:
    ac = assumption_check()
    sources = ac.load_sources()
    all_params = ac.load_parameters()
    mode_list = ["*", *ac.MODES]
    for name in PLUGINS:
        folder = ROOT / "plugins" / name
        manifest = json.loads(
            (folder / "mobsimlab-plugin.json").read_text(encoding="utf-8")
        )
        mode_list += [
            m["id"]
            for m in manifest.get("contributes", {}).get("modes", [])
            if m["id"] not in mode_list
        ]
        d = folder / "assumptions"
        sources.update({x["id"]: x for x in read_yaml(d / "sources.yaml")})
        all_params += [
            x
            for x in read_yaml(d / "parameters.yaml")
            if x.get("kind", "number") == "number"
        ]
    params = {}
    cited: set[str] = set()
    for p in all_params:
        entries: list[dict] = []
        modes = {m: index(entries, ac.resolve(p, m)) for m in mode_list}
        traction = {}
        for v in p["values"]:
            if set(v["context"]) == {"traction"}:
                for t in ac.as_list(v["context"]["traction"]):
                    traction[t] = index(entries, v)
        for e in entries:
            cited.update(e["sources"])
        row = {
            "used_by": list(p.get("used_by", [])),
            "entries": entries,
            "modes": {m: i for m, i in modes.items() if m == "*" or i != modes["*"]},
        }
        if traction:
            row["traction"] = traction
        params[p["key"]] = row
    data = {
        "_comment": "Generated by tools/assumptions-report/export_sources.py from assumptions/. Do not edit by hand.",
        "sources": {
            sid: {
                "title": s["title"],
                "publisher": s.get("publisher", ""),
                "url": s.get("url", ""),
                "access": s.get("access", ""),
            }
            for sid, s in sorted(sources.items())
            if sid in cited
        },
        "params": params,
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run tools/assumptions-report/export_sources.py",
                file=sys.stderr,
            )
            return 1
        print("OK: assumptions report sources up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
