#!/usr/bin/env python3
"""Export the cargo bike plugin's parameters for the cargo bike engine and the Cargo bike tab.

Usage:
  python3 tools/cargo-bike/export_defaults.py           # write crates/cargo-bike/data/defaults.json
  python3 tools/cargo-bike/export_defaults.py --check   # fail if it is stale

Reads plugins/cargo-bike/assumptions/parameters.yaml (validated by tools/plugins/check.py) and writes every
cargo_bike.* parameter as {label, unit, low, central, high} from its global entry, and the example kit presets
of plugins/cargo-bike/kits.json (their keys must be parameters, the default kit must exist). The Rust crate
reads the file at compile time and gives it to the Cargo bike tab.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "plugins" / "cargo-bike" / "assumptions" / "parameters.yaml"
KITS = ROOT / "plugins" / "cargo-bike" / "kits.json"
OUT = ROOT / "crates" / "cargo-bike" / "data" / "defaults.json"
PREFIX = "cargo_bike."


def render() -> str:
    """The defaults file as JSON text."""
    params = yaml.safe_load(SRC.read_text(encoding="utf-8")) or []
    out: dict = {}
    for p in params:
        if not p["key"].startswith(PREFIX):
            continue
        glob = next(
            v for v in p["values"] if (v.get("context") or {}).get("mode", "*") == "*"
        )
        out[p["key"][len(PREFIX) :]] = {
            "label": p["label"],
            "unit": p["unit"],
            "low": glob.get("low", glob["central"]),
            "central": glob["central"],
            "high": glob.get("high", glob["central"]),
        }
    kits = json.loads(KITS.read_text(encoding="utf-8"))
    ids = [k["id"] for k in kits["kits"]]
    if len(set(ids)) != len(ids) or kits["default"] not in ids:
        raise SystemExit(
            f"{KITS.relative_to(ROOT)}: kit ids must be unique and include the default"
        )
    for k in kits["kits"]:
        for key, v in k["values"].items():
            if key not in out or not isinstance(v, (int, float)):
                raise SystemExit(
                    f"{KITS.relative_to(ROOT)}: kit {k['id']} sets unknown or non-numeric {key}"
                )
    data = {
        "_comment": (
            "Generated by tools/cargo-bike/export_defaults.py from "
            "plugins/cargo-bike/assumptions/parameters.yaml and plugins/cargo-bike/kits.json. "
            "Do not edit by hand."
        ),
        "params": out,
        "default_kit": kits["default"],
        "kits": kits["kits"],
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    """Write or check the defaults file. Output: the exit code."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run tools/cargo-bike/export_defaults.py",
                file=sys.stderr,
            )
            return 1
        print("OK: cargo bike defaults up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
