#!/usr/bin/env python3
"""Export every parameter of the assumption library for Project Preferences → Parameters.

Usage:
  python3 tools/parameters/export_defaults.py           # write apps/web/src/workspace/parameters.generated.json
  python3 tools/parameters/export_defaults.py --check   # fail if it is stale

Reads assumptions/parameters (validated by tools/assumptions/check.py) and writes each parameter with its
label, group, unit and kind, and its [low, central, high] value for every mode ("*" and each mode whose value
differs) and for each traction that has its own entry. Enum and string parameters carry their central value
only. switch.default_turnout is left out: Project Preferences → Switches sets it per rail mode.

Plugin parameters that the tools read from Project Preferences are added from the plugins' own files
(PLUGINS), numbers only, each with the id of its plugin so Project Preferences lists them only while the plugin
is on: the noise map, the cable car, ferry and on-demand bus tools and the energy figures take every number
preference over the plugin's value. Their values are also given for the plugins' own modes (cable_car, ferry…).
The cargo bike plugin keeps its own values in its tab, so it is left out.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps" / "web" / "src" / "workspace" / "parameters.generated.json"
SKIP = {"switch.default_turnout"}
# Plugins whose number parameters the tools read from Project Preferences (also in
# tools/assumptions-report/export_sources.py).
PLUGINS = ["noise", "aerial-lift", "ferry", "on-demand-bus", "energy"]


def plugin_params() -> tuple[list[dict], list[str]]:
    """The number parameters of PLUGINS, each with `plugin` set to its plugin's id, and the plugins' own modes."""
    params: list[dict] = []
    modes: list[str] = []
    for name in PLUGINS:
        folder = ROOT / "plugins" / name
        manifest = json.loads(
            (folder / "mobsimlab-plugin.json").read_text(encoding="utf-8")
        )
        modes += [m["id"] for m in manifest.get("contributes", {}).get("modes", [])]
        for p in (
            yaml.safe_load(
                (folder / "assumptions" / "parameters.yaml").read_text(encoding="utf-8")
            )
            or []
        ):
            # Only numbers: the tools read number preferences, not enum choices.
            if p.get("kind", "number") == "number":
                params.append({**p, "plugin": manifest["id"]})
    return params, modes


def assumption_check():
    """tools/assumptions/check.py as a module (its parameter loader, mode list and resolve rule)."""
    spec = importlib.util.spec_from_file_location(
        "assumption_check", ROOT / "tools" / "assumptions" / "check.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def value(v: dict, kind: str):
    if kind != "number":
        return v["central"]
    return [v.get("low", v["central"]), v["central"], v.get("high", v["central"])]


def render() -> str:
    ac = assumption_check()
    params = [p for p in ac.load_parameters() if p["key"] not in SKIP]
    extra, plugin_modes = plugin_params()
    params += extra
    modes = ["*", *ac.MODES, *[m for m in plugin_modes if m not in ac.MODES]]
    # The library's groups first, then the plugins' own groups in the order they come.
    groups = list(ac.GROUP_ORDER)
    for p in params:
        if p["group"] not in groups:
            groups.append(p["group"])
    order = {g: i for i, g in enumerate(groups)}
    params.sort(key=lambda p: order[p["group"]])
    out = []
    for p in params:
        kind = p.get("kind", "number")
        by_mode = {m: value(ac.resolve(p, m), kind) for m in modes}
        glob = by_mode["*"]
        traction = {}
        for v in p["values"]:
            if set(v["context"]) == {"traction"}:
                for t in ac.as_list(v["context"]["traction"]):
                    traction[t] = value(v, kind)
        row = {
            "id": p["key"],
            "label": p["label"],
            "group": p["group"],
            "unit": p.get("unit", ""),
            "kind": kind,
            "values": {m: x for m, x in by_mode.items() if m == "*" or x != glob},
        }
        if "options" in p:
            row["options"] = p["options"]
        if traction:
            row["traction"] = traction
        if "plugin" in p:
            row["plugin"] = p["plugin"]
        out.append(row)
    data = {
        "_comment": "Generated by tools/parameters/export_defaults.py from assumptions/parameters. Do not edit by hand.",
        "groups": [g for g in groups if any(p["group"] == g for p in out)],
        "params": out,
    }
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run tools/parameters/export_defaults.py",
                file=sys.stderr,
            )
            return 1
        print("OK: parameter defaults up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
